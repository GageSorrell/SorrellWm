import * as Consumer from "../../Consumer/Config/Config.ts";
import { Command, Flag } from "@sorrell/effect/unstable/cli";
import { CodeAuger } from "./Utility.ts";
import { pipe } from "effect";

/* eslint-disable @typescript-eslint/typedef */

export/**
       * The config that is passed on to all subcommands.
       */
const SharedFlags =
    {
        Config: pipe(
            Flag.fileSchema("config", Consumer.Schema),
            Flag.withAlias("c"),
            Flag.withDefault(`${ CodeAuger }.config`),
            Flag.withDescription("The path to the `code-auger` config file of your package."),
            Flag.withMetavar("ConfigFilePath")
        ),
        Cwd: pipe(
            Flag.directory("cwd", { mustExist: true }),
            Flag.withDefault(process.cwd()),
            Flag.withDescription("The directory in which the command will operate."),
            Flag.withMetavar("Path")
        ),
        Silent: pipe(
            Flag.boolean("silent"),
            Flag.withAlias("s"),
            Flag.withDefault(false),
            Flag.withDescription("Suppress output to `stdout` and `stderr`.")
        )
    } satisfies Command.Command.Config;

export/**
       * The root command that wraps all commands in this application.
       */
const RootCommand =
    pipe(
        Command.make("code-auger"),
        Command.withDescription("A CLI tool for managing code auto-generated by your dependencies."),
        Command.withSharedFlags(SharedFlags)
    );

